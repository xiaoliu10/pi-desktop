export type Locale = AppSettings['language'];
export type TextKey = keyof (typeof dict)['en'];

export function translate(locale: Locale, key: TextKey, params?: Record<string, string | number>): string {
  let text: string = dict[locale][key] ?? dict.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}
