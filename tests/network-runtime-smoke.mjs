// Offline bundled-runtime smoke: temp agent config, loopback-only endpoint, no real sessions.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { spawn } from 'node:child_process';
import assert from 'node:assert/strict';
const root = process.cwd();
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'pi-network-smoke-'));
const server = net.createServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const port = server.address().port;
await new Promise(resolve => server.close(resolve));
const agent = path.join(tmp, 'agent'); fs.mkdirSync(agent);
fs.writeFileSync(path.join(agent, 'settings.json'), JSON.stringify({ retry: { enabled: false }, packages: [] }));
fs.writeFileSync(path.join(agent, 'models.json'), JSON.stringify({ providers: { 'offline-smoke': { baseUrl: `http://127.0.0.1:${port}/v1`, api: 'openai-completions', apiKey: 'dummy-local-only', models: [{ id: 'smoke', name: 'smoke', reasoning: false, input: ['text'], cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 }, contextWindow: 4096, maxTokens: 64 }] } } }));
const session = path.join(tmp, 'session.jsonl');
const child = spawn(process.execPath, [path.join(root, 'resources/pi-runtime/node_modules/@earendil-works/pi-coding-agent/dist/bundle/cli.js'), '--offline', '--no-extensions', '-e', path.join(root, 'extensions/desktop-policy/index.mjs'), '--no-skills', '--no-prompt-templates', '--no-context-files', '--no-themes', '--no-tools', '--provider', 'offline-smoke', '--model', 'smoke', '--session', session, '--mode', 'json', '--print', 'Reply ok'], { cwd: tmp, env: { ...process.env, PI_CODING_AGENT_DIR: agent, PI_DESKTOP_PERMISSION: 'ask', PI_OFFLINE: '1' }, stdio: ['ignore', 'pipe', 'pipe'] });
let stdout = '', stderr = '';
child.stdout.on('data', d => stdout += d); child.stderr.on('data', d => stderr += d);
const timer = setTimeout(() => child.kill('SIGTERM'), 45000);
const exit = await new Promise(resolve => child.on('close', resolve)); clearTimeout(timer);
fs.writeFileSync(path.join(tmp, 'stdout.jsonl'), stdout); fs.writeFileSync(path.join(tmp, 'stderr.txt'), stderr);
const entries = fs.readFileSync(session, 'utf8').trim().split('\n').map(line => JSON.parse(line));
const failed = entries.findLast(e => e.message?.role === 'assistant' && e.message.stopReason === 'error');
assert.ok(failed, `No persisted error. exit=${exit}, stderr=${stderr}`);
assert.ok(failed.message.errorMessage);
assert.ok(!failed.message.errorMessage.includes('dummy-local-only'));
console.log(JSON.stringify({ tmp, exit, errorMessage: failed.message.errorMessage, preservesCause: /ECONNREFUSED/.test(failed.message.errorMessage) }));
